// Generated by CMakeLists.txt from engine/editor/avatars/*.png; ends with a null name.
struct EmbeddedAvatar {
    const char* name;
    const unsigned char* data;
    size_t size;
};
extern const EmbeddedAvatar kEmbeddedAvatars[];

bool EditorAvatarPreset(const std::string& name, const unsigned char** data, size_t* size) {
    for (const EmbeddedAvatar* avatar = kEmbeddedAvatars; avatar->name; ++avatar) {
        if (name != avatar->name) continue;
        if (data) *data = avatar->data;
        if (size) *size = avatar->size;
        return true;
    }
    return false;
}

