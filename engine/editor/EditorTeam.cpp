constexpr const char* kAgentPayload = "OE_AGENT";  // drag to reorder: agent id (char data)
constexpr size_t kMaxAvatarBytes = 16 * 1024 * 1024;
constexpr int kMaxAvatarPixels = 8192;

std::shared_ptr<const Texture> DecodeAvatar(const unsigned char* data, size_t size) {
    int width = 0, height = 0;
    if (!data || size == 0 || size > kMaxAvatarBytes || !ImageDimensions(data, size, width, height)) return nullptr;
    if (width > kMaxAvatarPixels || height > kMaxAvatarPixels) return nullptr;
    auto texture = std::make_shared<Texture>();
    std::string error;
    if (!DecodeImage(data, size, *texture, &error)) return nullptr;
    return texture;
}

// First character of a UTF-8 text (its bytes), for the letter on a picture-less avatar.
std::string FirstCharacter(const std::string& text) {
    if (text.empty()) return "?";
    size_t length = 1;
    while (length < text.size() && (static_cast<unsigned char>(text[length]) & 0xC0) == 0x80) ++length;
    return text.substr(0, length);
}

ImU32 StateColor(const std::string& state, double time) {
    // Running states pulse so a glance tells who is busy.
    const int pulse = 150 + static_cast<int>(105.0 * (0.5 + 0.5 * std::sin(time * 5.0)));
    if (state == "queued") return IM_COL32(90, 150, 240, 255);
    if (state == "thinking") return IM_COL32(240, 180, 60, pulse);
    if (state == "working") return IM_COL32(90, 210, 110, pulse);
    if (state == "error") return IM_COL32(230, 80, 80, 255);
    return IM_COL32(140, 145, 155, 255);  // idle, offline
}

std::string ElapsedText(double seconds) {
    const int total = static_cast<int>(seconds);
    return Format("%d:%02d", total / 60, total % 60);
}

